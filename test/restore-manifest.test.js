test('restore hypotheses are additive evidence; only an uncheckable file fails a passing T2 gate', async () => {
  const fixture = await reviewFixture();
  const hypothesesPath = join(fixture.dir, 'hypotheses.json');
  const verified = {
    id: 'present', statement: 'the target contains the marker',
    prediction: { kind: 'string-literal', value: 'present-marker' },
  };
  const refuted = {
    id: 'absent', statement: 'the target contains another marker',
    prediction: { kind: 'string-literal', value: 'absent-marker' },
  };
  const unverified = {
    id: 'unknown', statement: 'an unsupported prediction is checkable',
    prediction: { kind: 'unknown-channel', value: 'anything' },
  };
  try {
    for (const value of [[verified], [verified, refuted], [verified, unverified], [verified, refuted, unverified]]) {
      await writeFile(hypothesesPath, JSON.stringify(value));
      const review = await runRestoreReview(fixture.spec, { ...fixture.options, hypothesesPath });
      assert.equal(review.exitCode, 0, JSON.stringify(value));
      assert.equal(review.record.exit, 0);
      assert.deepEqual(review.record.gateFailures, []);
      assert.deepEqual(review.record.hypotheses.map((item) => item.status), value.map((item) => item.id === 'present' ? 'verified' : item.id === 'absent' ? 'refuted' : 'unverified'));
      if (value.some((item) => item.id !== 'present')) assert.match(review.consoleLines.join('\n'), /hypothesis outcomes do not change the T2 verdict/);
    }
    await writeFile(hypothesesPath, '[]');
    const empty = await runRestoreReview(fixture.spec, { ...fixture.options, hypothesesPath });
    assert.equal(empty.exitCode, 1);
    assert.ok(empty.record.gateFailures.some((failure) => /hypotheses could not be checked/.test(failure)));
    await writeFile(hypothesesPath, '{');
    const uncheckable = await runRestoreReview(fixture.spec, { ...fixture.options, hypothesesPath });
    assert.equal(uncheckable.exitCode, 1);
    assert.ok(uncheckable.record.gateFailures.some((failure) => /hypotheses could not be checked/.test(failure)));
    assert.ok(uncheckable.record.hypothesesError);
  } finally {
    await rm(fixture.dir, { recursive: true, force: true });
  }
});
