test('whole-program manifests use an empty request and all-functions evidence', () => {
  const item = baseCase();
  item.scope = 'whole-program';
  item.functions = [];
  item.expected.functions = 53;
  item.expected.matched = 53;
  const [normalized] = validateRestoreManifest({ schemaVersion: 1, kind: 'restore-gates', files: [item] });
  assert.deepEqual(normalized.scope, { kind: 'whole-program', functionNames: [] });
  const t2 = { ...measured(), scope: 'all-functions', functions: 53, matched: 53 };
  const result = evaluateRestoreResult({
    scope: 'whole-program', requested: Array(53).fill('FUN'), expected: item.expected,
    threshold: 0.9, t2, inventory: inventory(),
  });
  assert.equal(result.passed, true, result.failures.join('; '));
});

test('restore gate refuses blocked, low, partial, entry-only and count-mismatched T2 evidence', () => {
  assert.equal(evaluate().passed, true);
  const cases = [
    [{ ...measured(), status: 'blocked', score: null }, inventory()],
    [{ ...measured(), score: 0.85 }, inventory()],
    [{ ...measured(), score: Number.POSITIVE_INFINITY }, inventory()],
    [{ ...measured(), scope: 'entry' }, inventory()],
    [{ ...measured(), coverage: 0.5 }, inventory()],
    [{ ...measured(), functions: 2 }, inventory()],
    [{ ...measured(), matched: 0 }, inventory()],
    [{ ...measured(), belowThreshold: 1 }, inventory()],
    [measured(), { ...inventory(), inventoryComplete: false }],
    [measured(), { ...inventory(), truncated: true }],
    [measured(), { ...inventory(), timeStopped: true }],
    [measured(), { ...inventory(), analysisTimedOut: true }],
    [measured(), { ...inventory(), failed: 1 }],
  ];
  for (const [t2, listed] of cases) assert.equal(evaluate(t2, listed).passed, false);
  assert.equal(
    evaluate(measured(), inventory(), { functions: 1, matched: 1, belowThreshold: 0 }).passed,
    true,
  );
  assert.equal(evaluate(measured(), inventory(), { functions: 2, matched: 2, belowThreshold: 0 }).passed, false);
});

test('selected restore gates isolate unrelated decompile failures but reject failures inside the request', () => {
  const t2 = {
    ...measured(), inventoryComplete: false, inventoryEnumerationComplete: true, failed: 1,
    selectedCoverage: {
      complete: true, requested: 1,
      target: { complete: true, found: 1, decompiled: 1, missing: [], failed: [], ambiguous: [] },
      rebuilt: { complete: true, found: 1, decompiled: 1, missing: [], failed: [], ambiguous: [] },
      outsideScopeFailures: 1,
    },
  };
  const listed = { ...inventory(), inventoryComplete: false, enumerationComplete: true, failed: 1 };
  assert.equal(evaluate(t2, listed).passed, true);
  assert.equal(evaluate({ ...t2, inventoryComplete: true }, listed).passed, false, 'complete inventory cannot also report a decompile failure');
  assert.equal(evaluate({ ...t2, failed: null }, listed).passed, false);
  assert.equal(evaluate({ ...t2, inventoryEnumerationComplete: false }, listed).passed, false);
  assert.equal(evaluate({ ...t2, selectedCoverage: { ...t2.selectedCoverage, complete: false } }, listed).passed, false);
  assert.equal(evaluate(t2, { ...listed, truncated: true }).passed, false);
  assert.equal(evaluate(t2, { ...listed, timeStopped: true }).passed, false);
  assert.equal(evaluate(t2, { ...listed, analysisTimedOut: true }).passed, false);
  const fallback = structuredClone(t2);
  fallback.selectedCoverage.rebuilt.sourceFallback = ['main'];
  assert.equal(evaluate(fallback, listed).passed, false, 'source fallback is not rebuilt decompilation');
});

test('single-target parsing preserves a zero threshold and rejects invalid numbers', () => {
  const spec = parseSingleSpec(['target.exe', '--functions', 'main', '--draft', 'draft.c', '--threshold', '0']);
  assert.equal(spec.threshold, 0);
  for (const threshold of ['', 'NaN', '-0.1', '1.1']) {
    assert.throws(() => parseSingleSpec(['target.exe', '--functions', 'main', '--draft', 'draft.c', '--threshold', threshold]), RestoreUsageError);
  }
  assert.throws(() => parseSingleSpec(['target.exe', '--functions', 'main', '--draft', 'draft.c', '--page-size', '1.5']), RestoreUsageError);
});

test('gate records append as JSON lines and surface an unwritable destination', async () => {
  const dir = await mkdtemp(join(tmpdir(), 'dsh-rea-restore-record-'));
  try {
    const path = join(dir, 'nested', 'gates.jsonl');
    await appendGateRecord(path, { caseId: 'one', exit: 0 });
    await appendGateRecord(path, { caseId: 'two', exit: 1 });
    const lines = (await readFile(path, 'utf8')).trim().split(/\r?\n/).map((line) => JSON.parse(line));
    assert.deepEqual(lines.map((line) => line.caseId), ['one', 'two']);
    assert.equal(await appendGateRecord('none', { caseId: 'ignored', exit: 0 }), null);
    await assert.rejects(() => appendGateRecord(dir, { caseId: 'bad', exit: 0 }));
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
});

async function reviewFixture() {
  const dir = await mkdtemp(join(tmpdir(), 'dsh-rea-restore-review-'));
  const target = join(dir, 'target.bin');
  const draft = join(dir, 'draft.c');
  await writeFile(target, 'present-marker');
  await writeFile(draft, 'int main(void) { return 0; }\n');
  const spec = {
    target, draft, scope: { kind: 'selected-functions', functionNames: ['main'] },
    metric: 'semantic', threshold: 0.9, pageSize: 200,
    expected: { functions: 1, matched: 1, belowThreshold: 0 },
  };
  const listed = {
    ...inventory(), enumerationComplete: true, total: 1, emitted: 1, pages: 1, pageSize: 200,
    functions: [{ name: 'main', rva: '0x1000', size: 16, cfg: {}, body: 'int main(void) { return helper(); }' }],
  };
  return {
    dir, spec,
    options: {
      outDir: join(dir, 'out'), recordPath: 'none',
      readyBuild: async () => ({ ready: true }),
      listFunctions: async () => listed,
      build: async ({ workDir }) => {
        await mkdir(workDir, { recursive: true });
        const outPath = join(workDir, 'restored.exe');
        await writeFile(outPath, 'rebuilt');
        return { ok: true, outPath, compiler: 'test-gcc', sha256: createHash('sha256').update('rebuilt').digest('hex') };
      },
      compare: async () => ({ tiers: { t2: measured() } }),
    },
  };
}

test('restore CLI classifies missing and invalid input data as exit 1', async () => {
  const dir = await mkdtemp(join(tmpdir(), 'dsh-rea-restore-input-'));
  const script = fileURLToPath(new URL('../scripts/recon/restore.mjs', import.meta.url));
  const target = join(dir, 'missing.exe');
  const draft = join(dir, 'missing.c');
  const manifestPath = join(dir, 'manifest.json');
  const run = (args) => spawnSync(process.execPath, [script, ...args], { encoding: 'utf8' });
  try {
    assert.equal(run(['--manifest', manifestPath]).status, 1);
    await writeFile(manifestPath, '{');
    assert.equal(run(['--manifest', manifestPath]).status, 1);
    const value = manifest();
    value.files[0].target = target;
    value.files[0].draft = draft;
    await writeFile(manifestPath, JSON.stringify(value));
    assert.equal(run(['--manifest', manifestPath]).status, 1);
    assert.equal(run([target, '--functions', 'main', '--draft', draft]).status, 1);
    assert.equal(run(['--manifest']).status, 2);
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
});

test('restore review rejects a build whose measured digest does not match its bytes', async () => {
  const fixture = await reviewFixture();
  let compared = false;
  try {
    const review = await runRestoreReview(fixture.spec, {
      ...fixture.options,
      build: async ({ workDir }) => {
        await mkdir(workDir, { recursive: true });
        const outPath = join(workDir, 'restored.exe');
        await writeFile(outPath, 'rebuilt');
        return { ok: true, outPath, compiler: 'test-gcc', sha256: 'f'.repeat(64) };
      },
      compare: async () => { compared = true; return { tiers: { t2: measured() } }; },
    });
    assert.equal(compared, false);
    assert.equal(review.exitCode, 1);
    assert.match(review.record.gateFailures.join(' '), /rebuilt SHA does not match the build result/);
  } finally {
    await rm(fixture.dir, { recursive: true, force: true });
  }
});

